#!/usr/bin/env node
/**
 * Builds the Figma token plugin from the CSS tokens.
 *
 * Reads src/tokens/{palette,scale,semantic}.css and writes
 * ../figma-plugin/code.js = token data + plugin runtime.
 * The CSS stays the single source of truth; the plugin is regenerated.
 *
 * Run: npm run figma:tokens
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const TOKENS = join(ROOT, 'src', 'tokens')
const PLUGIN = join(ROOT, '..', 'figma-plugin')

/** { name: value } for every custom property in a CSS block body. */
function declarations(body) {
  const out = {}
  const clean = body.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const decl of clean.split(';')) {
    const m = decl.match(/^\s*--([\w-]+)\s*:\s*([\s\S]+?)\s*$/)
    if (m) out[m[1]] = m[2].replace(/\s+/g, ' ')
  }
  return out
}

/** Body of the first block whose selector matches. */
function block(css, selectorRe) {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const re = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = re.exec(clean))) {
    if (selectorRe.test(m[1].trim())) return m[2]
  }
  throw new Error(`block not found: ${selectorRe}`)
}

const read = (f) => readFileSync(join(TOKENS, f), 'utf8')

const data = {
  palette: declarations(block(read('palette.css'), /^:root$/)),
  scale: declarations(block(read('scale.css'), /^:root$/)),
  dark: declarations(block(read('semantic.css'), /data-theme="dark"/)),
  light: declarations(block(read('semantic.css'), /^\[data-theme="light"\]$/)),
}

// --- Icons: the same geometry Icon.jsx renders, as standalone SVG ---
const { ICONS, PACKS } = await import(new URL('../src/icons/paths.js', import.meta.url))
const attr = (o) => Object.entries(o).map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}="${v}"`).join(' ')
// Stroke width comes from --icon-stroke, the same token Icon.jsx renders with
const STROKE_W = Number(data.scale['icon-stroke'])
if (!STROKE_W) throw new Error('--icon-stroke not found in scale.css')
const icons = Object.entries(ICONS).map(([name, icon]) => {
  const shared = icon.fill
    ? { fill: '#000000', stroke: 'none' }
    : { fill: 'none', stroke: '#000000', strokeWidth: STROKE_W, strokeLinecap: 'round', strokeLinejoin: 'round' }
  const els = icon.el || [['path', { d: icon.d }]]
  const body = els
    .map(([tag, a]) => {
      const merged = { ...shared, ...a }
      if (merged.fill === 'currentColor') merged.fill = '#000000'
      if (merged.stroke === 'currentColor') merged.stroke = '#000000'
      if (merged.strokeWidth === 'var(--icon-stroke)') merged.strokeWidth = STROKE_W
      return `<${tag} ${attr(merged)}/>`
    })
    .join('')
  return { name, pack: icon.pack, svg: `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${body}</svg>` }
})

const runtime = readFileSync(join(PLUGIN, 'runtime.js'), 'utf8')
writeFileSync(
  join(PLUGIN, 'code.js'),
  `// GENERATED by app/scripts/build-figma-tokens.mjs — do not edit.\n` +
    `// Edit src/tokens/*.css, src/icons/paths.js or figma-plugin/runtime.js, then npm run figma:tokens.\n\n` +
    `const TOKENS = ${JSON.stringify(data, null, 2)};\n\n` +
    `const ICON_PACKS = ${JSON.stringify(PACKS)};\n` +
    `const ICONS = ${JSON.stringify(icons, null, 1)};\n\n${runtime}`,
)

const n = Object.values(data).reduce((s, d) => s + Object.keys(d).length, 0)
console.log(`✓ figma-plugin/code.js: ${n} declarations, ${icons.length} icons`)
